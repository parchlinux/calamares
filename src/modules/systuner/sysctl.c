static void key_to_proc_path(const char *key, char *out_path, size_t out_size)
{
    char subpath[128];
    snprintf(subpath, sizeof(subpath), "%s", key);
    for (size_t i = 0; subpath[i] != '\0'; i++) {
        if (subpath[i] == '.') {
            subpath[i] = '/';
        }
    }
    snprintf(out_path, out_size, "/proc/sys/%s", subpath);
}

int systuner_populate_current_values(systuner_config_t *config)
{
    if (!config) {
        return -EINVAL;
    }

    for (size_t i = 0; i < config->param_count; i++) {
        systuner_param_t *p = &config->params[i];
        char path[256];
        key_to_proc_path(p->key, path, sizeof(path));

        FILE *fp = fopen(path, "r");
        if (fp) {
            unsigned long long val = 0;
            if (fscanf(fp, "%llu", &val) == 1) {
                p->current_val = (uint64_t)val;
                p->has_current_val = true;
            } else {
                p->has_current_val = false;
            }
            fclose(fp);
        } else {
            p->has_current_val = false;
        }
    }

    return 0;
}

int systuner_render_sysctl(const systuner_config_t *config, char *buffer, size_t bufsize)
{
    if (!config || !buffer || bufsize == 0) {
        return -EINVAL;
    }

    double ram_gib = (double)config->sysinfo.total_ram_bytes / (1024.0 * 1024.0 * 1024.0);
    double swap_gib = (double)config->sysinfo.total_swap_bytes / (1024.0 * 1024.0 * 1024.0);

    size_t written = 0;
    int n = snprintf(buffer + written, bufsize - written,
                     "# Configuration generated by Systuner %s\n"
                     "# Copyright (C) 2026 Parch GNU/Linux (AGPL-3.0)\n"
                     "#\n"
                     "# Target Profile : %s\n"
                     "# Hostname       : %s\n"
                     "# Kernel         : %s\n"
                     "# Total RAM      : %.2f GiB\n"
                     "# Swap           : %.2f GiB (ZRAM: %s)\n"
                     "# Primary Storage: %s\n"
                     "# Power Source   : %s\n"
                     "#\n\n",
                     SYSTUNER_VERSION,
                     systuner_profile_to_string(config->profile),
                     config->sysinfo.hostname,
                     config->sysinfo.kernel_release,
                     ram_gib,
                     swap_gib,
                     config->sysinfo.has_zram ? "yes" : "no",
                     systuner_storage_to_string(config->sysinfo.storage_type),
                     config->sysinfo.is_battery_powered ? "Battery/Laptop" : "AC/Desktop");

    if (n < 0 || (size_t)n >= bufsize - written) {
        return -ENOMEM;
    }
    written += (size_t)n;

    for (size_t i = 0; i < config->param_count; i++) {
        const systuner_param_t *p = &config->params[i];
        n = snprintf(buffer + written, bufsize - written,
                     "# %s\n%s = %" PRIu64 "\n\n",
                     p->description,
                     p->key,
                     p->recommended_val);

        if (n < 0 || (size_t)n >= bufsize - written) {
            return -ENOMEM;
        }
        written += (size_t)n;
    }

    return (int)written;
}

int systuner_render_json(const systuner_config_t *config, char *buffer, size_t bufsize)
{
    if (!config || !buffer || bufsize == 0) {
        return -EINVAL;
    }

    size_t written = 0;
    int n = snprintf(buffer + written, bufsize - written,
                     "{\n"
                     "  \"version\": \"%s\",\n"
                     "  \"profile\": \"%s\",\n"
                     "  \"system\": {\n"
                     "    \"hostname\": \"%s\",\n"
                     "    \"kernel\": \"%s\",\n"
                     "    \"total_ram_bytes\": %" PRIu64 ",\n"
                     "    \"total_swap_bytes\": %" PRIu64 ",\n"
                     "    \"cpu_cores\": %" PRIu32 ",\n"
                     "    \"has_zram\": %s,\n"
                     "    \"is_battery_powered\": %s,\n"
                     "    \"storage_type\": \"%s\"\n"
                     "  },\n"
                     "  \"parameters\": [\n",
                     SYSTUNER_VERSION,
                     systuner_profile_to_string(config->profile),
                     config->sysinfo.hostname,
                     config->sysinfo.kernel_release,
                     config->sysinfo.total_ram_bytes,
                     config->sysinfo.total_swap_bytes,
                     config->sysinfo.cpu_cores,
                     config->sysinfo.has_zram ? "true" : "false",
                     config->sysinfo.is_battery_powered ? "true" : "false",
                     systuner_storage_to_string(config->sysinfo.storage_type));

    if (n < 0 || (size_t)n >= bufsize - written) {
        return -ENOMEM;
    }
    written += (size_t)n;

    for (size_t i = 0; i < config->param_count; i++) {
        const systuner_param_t *p = &config->params[i];
        char cur_str[64];
        if (p->has_current_val) {
            snprintf(cur_str, sizeof(cur_str), "%" PRIu64, p->current_val);
        } else {
            snprintf(cur_str, sizeof(cur_str), "null");
        }

        n = snprintf(buffer + written, bufsize - written,
                     "    {\n"
                     "      \"key\": \"%s\",\n"
                     "      \"recommended\": %" PRIu64 ",\n"
                     "      \"current\": %s,\n"
                     "      \"description\": \"%s\"\n"
                     "    }%s\n",
                     p->key,
                     p->recommended_val,
                     cur_str,
                     p->description,
                     (i + 1 < config->param_count) ? "," : "");

        if (n < 0 || (size_t)n >= bufsize - written) {
            return -ENOMEM;
        }
        written += (size_t)n;
    }

    n = snprintf(buffer + written, bufsize - written, "  ]\n}\n");
    if (n < 0 || (size_t)n >= bufsize - written) {
        return -ENOMEM;
    }
    written += (size_t)n;

    return (int)written;
}

int systuner_render_table(const systuner_config_t *config, char *buffer, size_t bufsize)
{
    if (!config || !buffer || bufsize == 0) {
        return -EINVAL;
    }

    size_t written = 0;
    int n = snprintf(buffer + written, bufsize - written,
                     "+---------------------------------+-----------------+-----------------+----------+\n"
                     "| Sysctl Parameter                | Current Value   | Recommended     | Status   |\n"
                     "+---------------------------------+-----------------+-----------------+----------+\n");

    if (n < 0 || (size_t)n >= bufsize - written) {
        return -ENOMEM;
    }
    written += (size_t)n;

    for (size_t i = 0; i < config->param_count; i++) {
        const systuner_param_t *p = &config->params[i];
        char cur_buf[32];
        const char *status = "OK";

        if (p->has_current_val) {
            snprintf(cur_buf, sizeof(cur_buf), "%" PRIu64, p->current_val);
            if (p->current_val != p->recommended_val) {
                status = "CHANGE";
            }
        } else {
            snprintf(cur_buf, sizeof(cur_buf), "N/A");
            status = "NEW";
        }

        char rec_buf[32];
        snprintf(rec_buf, sizeof(rec_buf), "%" PRIu64, p->recommended_val);

        n = snprintf(buffer + written, bufsize - written,
                     "| %-31s | %15s | %15s | %-8s |\n",
                     p->key,
                     cur_buf,
                     rec_buf,
                     status);

        if (n < 0 || (size_t)n >= bufsize - written) {
            return -ENOMEM;
        }
        written += (size_t)n;
    }

    n = snprintf(buffer + written, bufsize - written,
                 "+---------------------------------+-----------------+-----------------+----------+\n");
    if (n < 0 || (size_t)n >= bufsize - written) {
        return -ENOMEM;
    }
    written += (size_t)n;

    return (int)written;
}

int systuner_apply_live(const systuner_config_t *config)
{
    if (!config) {
        return -EINVAL;
    }

    int applied_count = 0;
    for (size_t i = 0; i < config->param_count; i++) {
        const systuner_param_t *p = &config->params[i];
        char path[256];
        key_to_proc_path(p->key, path, sizeof(path));

        FILE *fp = fopen(path, "w");
        if (!fp) {
            fprintf(stderr, "systuner: warning: failed to write %s: %s\n", path, strerror(errno));
            continue;
        }

        if (fprintf(fp, "%" PRIu64 "\n", p->recommended_val) > 0) {
            applied_count++;
        }
        fclose(fp);
    }

    return applied_count;
}

int systuner_write_file(const systuner_config_t *config, const char *filepath)
{
    if (!config || !filepath) {
        return -EINVAL;
    }

    size_t bufsize = 8192;
    char *buf = malloc(bufsize);
    if (!buf) {
        return -ENOMEM;
    }

    int rc = systuner_render_sysctl(config, buf, bufsize);
    if (rc < 0) {
        free(buf);
        return rc;
    }

    FILE *fp = fopen(filepath, "w");
    if (!fp) {
        int err = errno;
        free(buf);
        return -err;
    }

    size_t to_write = (size_t)rc;
    size_t written = fwrite(buf, 1, to_write, fp);
    fclose(fp);
    free(buf);

    if (written != to_write) {
        return -EIO;
    }

    return 0;
}
